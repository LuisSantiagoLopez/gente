const byTitle = new Map(Object.values(icons).map((icon) => [icon.title.toLowerCase(), icon]));
export const logoKey = (name) => name.toLowerCase().replace(/[^a-z0-9]/g, "");
const rows = [];
for (const name of APPS) {
  const icon = byTitle.get(name.toLowerCase());
  if (!icon) throw new Error(`simple-icons has no "${name}"`);
  rows.push(
    `  ${JSON.stringify(logoKey(name))}: { hex: ${JSON.stringify(icon.hex)}, path: ${JSON.stringify(icon.path)} },`,
  );
}
writeFileSync(
  "apps/web/src/lib/integrations/app-logo-icons.ts",
  `// Generated by scripts/gente-app-logos.mjs from simple-icons (CC0). Do not edit by hand.\n` +
    `// Brand marks for common apps, keyed by name without spaces or punctuation.\n` +
    `export const APP_LOGO_ICONS: Readonly<Record<string, { hex: string; path: string }>> = {\n${rows.join("\n")}\n};\n`,
);
console.log(`wrote ${rows.length} app logos`);
